import json
import os
from PIL import Image

# Generates grid/carousel thumbnails in images/Thumb/, mirroring the folder
# structure of the full-size images (images/Cars/X.webp -> images/Thumb/Cars/X.webp).
# Re-run after adding new photos; existing up-to-date thumbnails are skipped.

SOURCE_DIRS = ["Aerial", "Astro", "BandW", "Cars", "Events", "Nature",
               "Night", "People", "Urban", "Album", "Prom"]
THUMB_ROOT = os.path.join("images", "Thumb")
THUMB_WIDTH = 800
QUALITY = 78

def make_thumb(src_path, dst_path):
    img = Image.open(src_path)
    if img.width > THUMB_WIDTH:
        h = round(img.height * THUMB_WIDTH / img.width)
        img = img.resize((THUMB_WIDTH, h), Image.LANCZOS)
    img.save(dst_path, format="WEBP", quality=QUALITY, method=6)

made = skipped = 0
for d in SOURCE_DIRS:
    src_dir = os.path.join("images", d)
    dst_dir = os.path.join(THUMB_ROOT, d)
    os.makedirs(dst_dir, exist_ok=True)
    for name in sorted(os.listdir(src_dir)):
        src = os.path.join(src_dir, name)
        if not (os.path.isfile(src) and name.lower().endswith(".webp")):
            continue
        dst = os.path.join(dst_dir, name)
        if os.path.exists(dst) and os.path.getmtime(dst) >= os.path.getmtime(src):
            skipped += 1
            continue
        make_thumb(src, dst)
        made += 1
        print(f"{dst}  {os.path.getsize(dst) // 1024} KB")

print(f"Done: {made} created, {skipped} up to date")

# Write image-sizes.js: the width/height of every gallery photo, keyed by its blur
# placeholder path (the `src` in gallery-data.js). The gallery puts these on each <img>
# so the browser reserves the right space before the image loads.
# Uses the thumbnail's exact size when there is one with the same shape, otherwise the
# blur placeholder's (e.g. photos only hosted on Cloudinary).
BLUR_ROOT = os.path.join("images", "Blur")
sizes = {}
for dirpath, _, files in os.walk(BLUR_ROOT):
    for name in sorted(files):
        if not name.lower().endswith(".webp"):
            continue
        blur_path = os.path.join(dirpath, name)
        rel = os.path.relpath(blur_path, BLUR_ROOT)
        with Image.open(blur_path) as im:
            w, h = im.size
        thumb_path = os.path.join(THUMB_ROOT, rel)
        if os.path.exists(thumb_path):
            with Image.open(thumb_path) as im:
                tw, th = im.size
            if abs(tw / th - w / h) < 0.03 * (w / h):
                w, h = tw, th
        sizes["images/Blur/" + rel.replace(os.sep, "/")] = (w, h)

with open("image-sizes.js", "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by make-thumbs.py - do not edit by hand.\n")
    f.write("window.IMAGE_SIZES = {\n")
    for key in sorted(sizes):
        w, h = sizes[key]
        f.write(f"  {json.dumps(key, ensure_ascii=False)}: [{w}, {h}],\n")
    f.write("};\n")
print(f"Wrote image-sizes.js ({len(sizes)} images)")
