// Lazy loading for gallery images.
// Each image starts with a tiny blurred placeholder in `src` and the real image in `data-src`.
// When an image comes within one screen of the viewport, the real image is downloaded and
// decoded in the background, then swapped in. Images in hidden categories (display: none)
// never intersect, so they load automatically once their category is shown.
function initLazyLoading() {
    const lazyImages = document.querySelectorAll('img[data-src]');
    if (!lazyImages.length) return;

    const loadImage = (img) => {
        const src = img.getAttribute('data-src');
        img.removeAttribute('data-src');
        img.classList.add('lazy-loading');

        const loader = new Image();
        loader.onload = () => {
            // Decode off the main thread before swapping, so scrolling stays smooth
            loader.decode().catch(() => {}).then(() => {
                img.src = src;
                img.classList.remove('lazy-loading');
                img.classList.add('lazy-loaded');
            });
        };
        loader.onerror = () => {
            img.classList.remove('lazy-loading');
            img.classList.add('lazy-error');
        };
        loader.src = src;
    };

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                observer.unobserve(entry.target);
                loadImage(entry.target);
            }
        });
    }, { rootMargin: `${window.innerHeight}px 0px` });

    lazyImages.forEach(img => observer.observe(img));
}

